fn main() -> Result<()> {
    let types = Types::default()
        .register::<koharu_protocol::Request>()
        .register::<koharu_protocol::ServerMessage>()
        .register::<koharu_protocol::AppEvent>();
    let types = specta_serde::PhasesFormat
        .map_types(&types)
        .map_err(|error| anyhow::anyhow!(error.to_string()))?
        .into_owned();
    let types = Configuration::empty()
        .enable_lossless_floats()
        .apply_types(&types)
        .into_owned();
    let generated = Typescript::default()
        .header("")
        .export(&types, IdentityFormat)?;
    ensure!(
        generated.contains("x: number,") && !generated.contains("x: number | null,"),
        "required lossless float fields must remain non-nullable"
    );
    ensure!(
        generated.contains("opacity: number | null,"),
        "optional float fields must remain nullable"
    );
    let output = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/koharu/lib/protocol.ts");
    std::fs::write(&output, format!("{COMMANDS}{generated}"))
        .with_context(|| format!("failed to generate {}", output.display()))?;
    Ok(())
}

/// The wire and semantic transforms are deliberately ordered above: serde
/// first, then lossless runtime semantics. The exporter must not remap the
/// completed graph a second time.
struct IdentityFormat;

impl Format for IdentityFormat {
    fn map_types(&self, types: &Types) -> Result<Cow<'_, Types>, FormatError> {
        Ok(Cow::Owned(types.clone()))
    }

    fn map_type(
        &self,
        _types: &Types,
        datatype: &DataType,
    ) -> Result<Cow<'_, DataType>, FormatError> {
        Ok(Cow::Owned(datatype.clone()))
    }
}
